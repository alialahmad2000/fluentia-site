export function planFor(lvl, goal, gender) {
  const k = gender === 'female' ? 'f' : 'm';
  const base = LEVEL_COPY[lvl].plan.map((p) => p[k]);
  const gl = GOAL_LINE[goal] || GOAL_LINE.confidence;
  return [...base, (lvl <= 2 ? gl.low : gl.high)[k]];
}

