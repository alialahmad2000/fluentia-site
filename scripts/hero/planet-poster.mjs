// The homepage planet's poster: one frame of the hero shader itself (F painted,
// dimmed, centred), rendered in software GL and saved as AVIF + WebP at the
// widths Hero.jsx asks for. Run against a local preview of the built site:
//   npx vite preview --port 4173 &
//   node scripts/hero/planet-poster.mjs [http://localhost:4173] [public/brand/hero]
// Needs `playwright-core` + `sharp` (not project dependencies) and Google Chrome.
import { chromium } from "playwright-core";
import sharp from "sharp";
import fs from "node:fs";

const base = process.argv[2] || "http://localhost:4173";
const out = process.argv[3] || "public/brand/hero";
const SIZE = 1040;
const WIDTHS = [360, 520, 720, 1040];
fs.mkdirSync(out, { recursive: true });

const browser = await chromium.launch({
  executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  // software GL: no GPU work on the host
  args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"],
});
const ctx = await browser.newContext({ viewport: { width: SIZE + 200, height: SIZE + 200 }, deviceScaleFactor: 1 });
await ctx.addInitScript(() => {
  try {
    localStorage.setItem("fl-intro-seen", "1");
    localStorage.setItem("fluentia_cookie_consent_v1", JSON.stringify({ necessary: true, analytics: false, marketing: false, decidedAt: new Date().toISOString() }));
  } catch {}
});
const page = await ctx.newPage();
await page.goto(`${base}/?tier=high`, { waitUntil: "load" });
await page.addStyleTag({
  content: `
    html, body, .fx-next { background: transparent !important; }
    .fx-stars, .fx-head, .fx-hero-copy, .fx-main > :not(#fx-top), .fx-footer, [aria-labelledby=fluentia-cookie-title] { display: none !important; }
    .fx-hero { display: block !important; padding: 0 !important; min-height: 0 !important; }
    .fx-hero-orb { position: fixed !important; top: 0 !important; left: 0 !important; width: ${SIZE}px !important; height: ${SIZE}px !important; transform: none !important; }
    .fx-orb-poster { display: none !important; }
  `,
});
await page.waitForSelector(".fx-hero-orb .fx-orb[data-live]", { timeout: 30000 });
await page.waitForTimeout(1800); // the canvas's own fade-in
const png = await page.locator(".fx-hero-orb .fx-orb").screenshot({ omitBackground: true });
await browser.close();
fs.writeFileSync(`${out}/planet-src.png`, png);
for (const w of WIDTHS) {
  const img = sharp(png).resize({ width: w });
  await img.clone().avif({ quality: 58, effort: 7 }).toFile(`${out}/planet-${w}.avif`);
  await img.clone().webp({ quality: 80, alphaQuality: 85 }).toFile(`${out}/planet-${w}.webp`);
}
// The tiny inline placeholder, as a module Hero imports, so it paints with the HTML.
const lqip = await sharp(png).resize({ width: 300 }).avif({ quality: 40, effort: 7 }).toBuffer();
fs.writeFileSync(
  "src/pages/next/planet-lqip.js",
  `// Generated by scripts/hero/planet-poster.mjs: a 300 px AVIF of the hero planet, inlined so it\n` +
    `// paints with the HTML (the planet is the homepage LCP). Do not edit by hand.\n` +
    `export default "data:image/avif;base64,${lqip.toString("base64")}";\n`,
);
fs.unlinkSync(`${out}/planet-src.png`);
console.log("poster written:", fs.readdirSync(out).join(" "));
